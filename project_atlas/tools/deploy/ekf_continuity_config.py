#!/usr/bin/env python3
"""Write an EKF params file whose initial_state equals the CURRENT parked /odom pose.

robot_localization starts at the origin. Restarting atlas-ekf after ATLAS has moved therefore makes
/odom (odom->base_link) jump back to (0,0,0) - 1.15 m / 34 deg in the native Humble check - and
AMCL would receive that jump as motion. Starting the new EKF at the parked pose removes the jump.

Used for BOTH the Candidate B deployment and its rollback. Read-only on the ROS graph (one /odom and
one /atlas/control_policy sample). Refuses unless the stop is latched, manual-only is on and /odom
shows no motion. The output differs from the source ONLY by initial_state (checked).
  ekf_continuity_config.py <source_params.yaml> <out_params.yaml>
"""
import copy, json, math, sys, time
import yaml

NODE = 'atlas_ekf'


def build(source_params, x, y, yaw):
    """Return a deep copy of the params with initial_state = (x, y, yaw), everything else equal."""
    for value in (x, y, yaw):
        if not math.isfinite(value):
            raise ValueError('non-finite pose')
    out = copy.deepcopy(source_params)
    p = out[NODE]['ros__parameters']
    if not p.get('two_d_mode', False):
        raise ValueError('expected two_d_mode true')
    p['initial_state'] = [float(x), float(y), 0.0, 0.0, 0.0, float(yaw)] + [0.0] * 9
    return out


def only_initial_state_differs(source_params, out_params):
    a = source_params[NODE]['ros__parameters']; b = out_params[NODE]['ros__parameters']
    keys = {k for k in set(a) | set(b) if a.get(k) != b.get(k)}
    return keys == {'initial_state'}


def read_parked_pose(timeout_s=10.0):
    import rclpy
    from nav_msgs.msg import Odometry
    from std_msgs.msg import String
    rclpy.init(); node = rclpy.create_node('ekf_continuity_readonly'); got = {}
    node.create_subscription(Odometry, '/odom', lambda m: got.setdefault('odom', m), 10)
    node.create_subscription(String, '/atlas/control_policy', lambda m: got.setdefault('policy', json.loads(m.data)), 10)
    end = time.monotonic() + timeout_s
    while time.monotonic() < end and len(got) < 2:
        rclpy.spin_once(node, timeout_sec=0.1)
    node.destroy_node(); rclpy.shutdown()
    if len(got) < 2:
        raise SystemExit('refusing: /odom or /atlas/control_policy not received')
    pol, o = got['policy'], got['odom']
    if pol.get('stop_latched') is not True or pol.get('manual_only') is not True:
        raise SystemExit(f'refusing: stop_latched={pol.get("stop_latched")} manual_only={pol.get("manual_only")}')
    t = o.twist.twist
    if max(abs(t.linear.x), abs(t.linear.y), abs(t.angular.z)) > 1e-3:
        raise SystemExit('refusing: /odom reports motion')
    q = o.pose.pose.orientation
    yaw = math.atan2(2 * (q.w * q.z + q.x * q.y), 1 - 2 * (q.y * q.y + q.z * q.z))
    return o.pose.pose.position.x, o.pose.pose.position.y, yaw


def main(src, dst):
    source = yaml.safe_load(open(src))
    x, y, yaw = read_parked_pose()
    out = build(source, x, y, yaw)
    if not only_initial_state_differs(source, out):
        raise SystemExit('refusing: output would differ by more than initial_state')
    with open(dst, 'w') as f:
        f.write(f'# generated by ekf_continuity_config.py from {src}; initial_state = parked /odom pose\n')
        yaml.safe_dump(out, f, sort_keys=False)
    print(json.dumps({'source': src, 'out': dst, 'x': round(x, 4), 'y': round(y, 4), 'yaw_deg': round(math.degrees(yaw), 3)}))


if __name__ == '__main__':
    main(*sys.argv[1:3])
